export function NodeIcon({ type, size = 16, className }: { type: string; size?: number; className?: string }) {
  const t = (type || '').toUpperCase().trim();
  switch (t) {
    case 'LEVEL':
      return <StageIcon size={size} className={className} />;
    case 'STREAM':
      return <StreamIcon size={size} className={className} />;
    case 'SUBJECT_COMBINATION':
      return <SubjectIcon size={size} className={className} />;
    case 'FIELD':
      return <FieldIcon size={size} className={className} />;
    case 'DEGREE':
    case 'POSTGRADUATE_PROGRAM':
      return <DegreeIcon size={size} className={className} />;
    case 'ROUTE':
      return <RouteIcon size={size} className={className} />;
    case 'CERTIFICATION':
      return <CertificationIcon size={size} className={className} />;
    case 'CAREER':
      return <CareerIcon size={size} className={className} />;
    case 'ENTRANCE_EXAM':
    case 'RECRUITMENT_EXAM':
      return <ExamIcon size={size} className={className} />;
    case 'COLLEGE':
    case 'COLLEGE_GROUP':
      return <CollegeIcon size={size} className={className} />;
    case 'SPECIALISATION':
      return <SpecialisationIcon size={size} className={className} />;
    case 'PROFESSION':
      return <ProfessionIcon size={size} className={className} />;
    case 'STUDY_ABROAD':
      return <GlobeIcon size={size} className={className} />;
    case 'CAREER_DOMAIN':
      return <DomainIcon size={size} className={className} />;
    default:
      return <FieldIcon size={size} className={className} />;
  }
}
